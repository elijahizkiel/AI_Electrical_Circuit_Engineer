from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class State(StrEnum):
    CREATED = "CREATED"; SCOPE_CHECK = "SCOPE_CHECK"; REQUIREMENTS_ANALYSIS = "REQUIREMENTS_ANALYSIS"
    NEEDS_CLARIFICATION = "NEEDS_CLARIFICATION"; REQUIREMENTS_READY = "REQUIREMENTS_READY"
    ARCHITECTURE_DESIGN = "ARCHITECTURE_DESIGN"; CIRCUIT_DESIGN = "CIRCUIT_DESIGN"; DESIGN_REVIEW = "DESIGN_REVIEW"
    DESIGN_REVISION = "DESIGN_REVISION"; DESIGN_APPROVAL = "DESIGN_APPROVAL"; SIMULATION_PREPARATION = "SIMULATION_PREPARATION"
    AWAITING_SIMULATION_APPROVAL = "AWAITING_SIMULATION_APPROVAL"; SIMULATION_RUNNING = "SIMULATION_RUNNING"
    WAVEFORM_ANALYSIS = "WAVEFORM_ANALYSIS"; REQUIREMENT_VERIFICATION = "REQUIREMENT_VERIFICATION"
    OPTIMIZATION_PROPOSAL = "OPTIMIZATION_PROPOSAL"; OPTIMIZATION_APPROVAL = "OPTIMIZATION_APPROVAL"
    NEXT_DESIGN_REVISION = "NEXT_DESIGN_REVISION"; REPORT_GENERATION = "REPORT_GENERATION"
    COMPLETED = "COMPLETED"; COMPLETED_WITH_WARNINGS = "COMPLETED_WITH_WARNINGS"; FAILED = "FAILED"; CANCELLED = "CANCELLED"


TERMINAL = {State.COMPLETED, State.COMPLETED_WITH_WARNINGS, State.FAILED, State.CANCELLED}

ALLOWED_TRANSITIONS: dict[State, set[State]] = {
    State.CREATED: {State.SCOPE_CHECK, State.CANCELLED},
    State.SCOPE_CHECK: {State.REQUIREMENTS_ANALYSIS, State.NEEDS_CLARIFICATION, State.FAILED, State.CANCELLED},
    State.REQUIREMENTS_ANALYSIS: {State.NEEDS_CLARIFICATION, State.REQUIREMENTS_READY, State.FAILED, State.CANCELLED},
    State.NEEDS_CLARIFICATION: {State.REQUIREMENTS_ANALYSIS, State.CANCELLED},
    State.REQUIREMENTS_READY: {State.ARCHITECTURE_DESIGN, State.CANCELLED},
    State.ARCHITECTURE_DESIGN: {State.CIRCUIT_DESIGN, State.FAILED, State.CANCELLED},
    State.CIRCUIT_DESIGN: {State.DESIGN_REVIEW, State.FAILED, State.CANCELLED},
    State.DESIGN_REVIEW: {State.DESIGN_REVISION, State.DESIGN_APPROVAL, State.FAILED, State.CANCELLED},
    State.DESIGN_REVISION: {State.CIRCUIT_DESIGN, State.CANCELLED},
    State.DESIGN_APPROVAL: {State.SIMULATION_PREPARATION, State.CANCELLED},
    State.SIMULATION_PREPARATION: {State.AWAITING_SIMULATION_APPROVAL, State.FAILED, State.CANCELLED},
    State.AWAITING_SIMULATION_APPROVAL: {State.SIMULATION_RUNNING, State.REPORT_GENERATION, State.CANCELLED},
    State.SIMULATION_RUNNING: {State.WAVEFORM_ANALYSIS, State.FAILED, State.CANCELLED},
    State.WAVEFORM_ANALYSIS: {State.REQUIREMENT_VERIFICATION, State.FAILED, State.CANCELLED},
    State.REQUIREMENT_VERIFICATION: {State.OPTIMIZATION_PROPOSAL, State.REPORT_GENERATION, State.CANCELLED},
    State.OPTIMIZATION_PROPOSAL: {State.OPTIMIZATION_APPROVAL, State.REPORT_GENERATION, State.CANCELLED},
    State.OPTIMIZATION_APPROVAL: {State.NEXT_DESIGN_REVISION, State.REPORT_GENERATION, State.CANCELLED},
    State.NEXT_DESIGN_REVISION: {State.CIRCUIT_DESIGN, State.CANCELLED},
    State.REPORT_GENERATION: {State.COMPLETED, State.COMPLETED_WITH_WARNINGS, State.FAILED, State.CANCELLED},
}


class CircuitAgentError(Exception): pass
class ScopeRejected(CircuitAgentError): pass
class ClarificationRequired(CircuitAgentError): pass
class SchemaValidationError(CircuitAgentError): pass
class ApprovalRequired(CircuitAgentError): pass
class SimulatorNotConfigured(CircuitAgentError): pass


@dataclass(frozen=True)
class ScopeResult:
    allowed: bool
    classification: str
    reasons: list[str]
